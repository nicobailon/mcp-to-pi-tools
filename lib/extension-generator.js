/**
 * Pi Extension Generator
 * Generates TypeScript pi extensions from MCP tool groups
 */

import { mergeToolSchemas, snakeToCamel, toolSchemaToTypeBox } from "./schema-converter.js";

/**
 * Generate the pi extension index.ts file
 * @param {object} options - Generation options
 * @param {string} options.serverName - MCP server name
 * @param {string} options.mcpCommand - Full MCP command for mcporter
 * @param {string} options.packageName - Original MCP package name
 * @param {Array} options.groups - Tool groups from AI grouping
 * @param {Array} options.tools - Original MCP tools with schemas
 * @param {string} [options.description] - Package description
 * @returns {string} - TypeScript code for index.ts
 */
export function generateExtension(options) {
  const { serverName, mcpCommand, packageName, groups, tools, description } = options;

  // Map MCP tools by name for quick lookup
  const toolMap = new Map(tools.map((t) => [t.name, t]));

  // Generate header
  const header = generateHeader(serverName, packageName, groups, description);

  // Generate imports
  const imports = generateImports();

  // Generate callMcp helper
  const callMcpHelper = generateCallMcpHelper(mcpCommand, serverName);

  // Generate extension function
  const extensionFn = generateExtensionFunction(serverName, groups, toolMap);

  return `${header}

${imports}

const MCP_COMMAND = "${escapeString(mcpCommand)}";
const SERVER_NAME = "${escapeString(serverName)}";

${callMcpHelper}

${extensionFn}
`;
}

/**
 * Escape content for use in a block comment (prevent breaking out with *​/)
 */
function escapeCommentContent(str) {
  if (!str) return "";
  // Replace */ with *\/ to prevent breaking out of comment
  return str.replace(/\*\//g, "*\\/");
}

/**
 * Generate file header comment
 */
function generateHeader(serverName, packageName, groups, description) {
  const toolNames = groups.map((g) => g.toolName).join(", ");
  const desc = description || `Pi extension for ${serverName} MCP server`;

  // Escape values that appear in the comment block
  const safeServerName = escapeCommentContent(serverName);
  const safePackageName = escapeCommentContent(packageName);
  const safeDesc = escapeCommentContent(desc);
  const safeToolNames = escapeCommentContent(toolNames);

  return `/**
 * ${safeServerName} MCP Extension
 * Generated by mcp2ext from ${safePackageName}
 * 
 * ${safeDesc}
 * 
 * Tools: ${safeToolNames}
 */`;
}

/**
 * Generate import statements
 */
function generateImports() {
  return `import type { ExtensionAPI } from "@mariozechner/pi-coding-agent";
import { Type } from "@sinclair/typebox";
import { StringEnum } from "@mariozechner/pi-ai";
import { execSync } from "node:child_process";`;
}

/**
 * Generate the callMcp helper function
 */
function generateCallMcpHelper(mcpCommand, serverName) {
  return `function callMcp(tool: string, params: Record<string, unknown> = {}): string {
  const paramStr = Object.entries(params)
    .filter(([_, v]) => v !== undefined)
    .map(([k, v]) => \`\${k}:\${JSON.stringify(v)}\`)
    .join(" ");
  
  const cmd = \`npx mcporter call --stdio "\${MCP_COMMAND}" \${SERVER_NAME}.\${tool} \${paramStr}\`;
  
  try {
    return execSync(cmd, { 
      encoding: "utf-8", 
      stdio: ["pipe", "pipe", "pipe"],
      timeout: 60000,
    });
  } catch (error: any) {
    throw new Error(error.stderr || error.message);
  }
}`;
}

/**
 * Generate the main extension function
 */
function generateExtensionFunction(serverName, groups, toolMap) {
  const fnName = serverNameToFunctionName(serverName);
  const toolRegistrations = groups.map((group) => generateToolRegistration(group, toolMap)).join("\n\n");

  return `export default function ${fnName}Extension(pi: ExtensionAPI) {
${toolRegistrations}
}`;
}

/**
 * Generate a single tool registration
 */
function generateToolRegistration(group, toolMap) {
  const { toolName, label, description, mcpTools, rationale } = group;

  // Get full tool definitions for tools in this group
  const groupTools = mcpTools.map((name) => toolMap.get(name)).filter(Boolean);

  if (groupTools.length === 0) {
    throw new Error(`No valid tools found for group: ${toolName}`);
  }

  const isMultiTool = groupTools.length > 1;

  // Generate schema
  let schemaCode;
  let paramMapping;

  if (isMultiTool) {
    const merged = mergeToolSchemas(groupTools, "action");
    schemaCode = merged.schema;
    paramMapping = merged.paramMapping;
  } else {
    schemaCode = toolSchemaToTypeBox(groupTools[0]);
    paramMapping = buildParamMapping(groupTools[0]);
  }

  // Generate execute function
  const executeCode = generateExecuteFunction(groupTools, paramMapping, isMultiTool);

  // Build the tool registration
  const mcpToolsList = mcpTools.join(", ");
  // Sanitize rationale for single-line comment (replace newlines with spaces, escape quotes)
  const sanitizedRationale = rationale
    ? rationale.replace(/[\r\n]+/g, " ").replace(/"/g, '\\"')
    : null;
  const rationaleComment = sanitizedRationale ? `  // AI rationale: "${sanitizedRationale}"` : "";

  return `  // Grouped tool: ${toolName} (wraps: ${mcpToolsList})
${rationaleComment}
  pi.registerTool({
    name: "${escapeString(toolName)}",
    label: "${escapeString(label)}",
    description: "${escapeString(description)}",
    parameters: ${indentCode(schemaCode, 4)},
    ${executeCode}
  });`;
}

/**
 * Generate the execute function for a tool
 */
function generateExecuteFunction(tools, paramMapping, isMultiTool) {
  if (isMultiTool) {
    return generateMultiToolExecute(tools, paramMapping);
  }
  return generateSingleToolExecute(tools[0], paramMapping);
}

/**
 * Generate execute for a single-tool group
 */
function generateSingleToolExecute(tool, paramMapping) {
  const paramConversions = generateParamConversions(paramMapping);

  return `async execute(toolCallId, params, onUpdate, ctx, signal) {
      if (signal?.aborted) {
        return { content: [{ type: "text", text: "Aborted" }], details: {} };
      }
      
      try {
        const mcpParams: Record<string, unknown> = {};
${paramConversions}
        
        const result = callMcp("${escapeString(tool.name)}", mcpParams);
        
        return { 
          content: [{ type: "text", text: result }],
          details: {},
        };
      } catch (error: any) {
        throw new Error(\`${escapeString(tool.name)} failed: \${error.message}\`);
      }
    }`;
}

/**
 * Generate execute for a multi-tool group
 */
function generateMultiToolExecute(tools, paramMapping) {
  // Generate switch cases for each action
  const cases = tools.map((tool) => {
    const toolParamMapping = buildParamMapping(tool);
    const paramAssignments = Object.entries(toolParamMapping)
      .map(([camel, snake]) => {
        const paramsAccess = propAccess("params", camel);
        const mcpAccess = propAccess("mcpParams", snake);
        return `          if (${paramsAccess} !== undefined) ${mcpAccess} = ${paramsAccess};`;
      })
      .join("\n");

    return `        case "${escapeString(tool.name)}":
${paramAssignments || "          // No parameters"}
          break;`;
  }).join("\n");

  return `async execute(toolCallId, params, onUpdate, ctx, signal) {
      if (signal?.aborted) {
        return { content: [{ type: "text", text: "Aborted" }], details: {} };
      }
      
      try {
        const mcpParams: Record<string, unknown> = {};
        
        // Map parameters based on action
        switch (params.action) {
${cases}
        }
        
        const result = callMcp(params.action, mcpParams);
        
        return { 
          content: [{ type: "text", text: result }],
          details: { action: params.action },
        };
      } catch (error: any) {
        throw new Error(\`\${params.action} failed: \${error.message}\`);
      }
    }`;
}

/**
 * Check if a name is a valid JavaScript identifier
 * @param {string} name - Name to check
 * @returns {boolean}
 */
function isValidJsIdentifier(name) {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name);
}

/**
 * Generate property access code (dot or bracket notation)
 * @param {string} obj - Object name
 * @param {string} prop - Property name
 * @returns {string} - Property access code
 */
function propAccess(obj, prop) {
  if (isValidJsIdentifier(prop)) {
    return `${obj}.${prop}`;
  }
  return `${obj}["${escapeString(prop)}"]`;
}

/**
 * Generate parameter conversion code for single-tool execute
 */
function generateParamConversions(paramMapping) {
  return Object.entries(paramMapping)
    .map(([camel, snake]) => {
      const paramsAccess = propAccess("params", camel);
      const mcpAccess = propAccess("mcpParams", snake);
      return `        if (${paramsAccess} !== undefined) ${mcpAccess} = ${paramsAccess};`;
    })
    .join("\n");
}

// Note: buildParamMapping is imported from schema-converter.js but we keep a local version
// to avoid a circular dependency issue when this file is loaded before schema-converter
// is fully initialized. The implementations are identical.
/**
 * Build parameter name mapping for a tool
 */
function buildParamMapping(tool) {
  const mapping = {};
  const props = tool.inputSchema?.properties || {};

  for (const snakeName of Object.keys(props)) {
    const camelName = snakeToCamel(snakeName);
    mapping[camelName] = snakeName;
  }

  return mapping;
}

/**
 * Convert server name to function name (camelCase, valid identifier)
 */
function serverNameToFunctionName(serverName) {
  if (!serverName) return "mcp";

  // chrome-devtools -> chromeDevtools
  // 123-server -> _123Server (prepend underscore for leading digits)
  // has spaces -> hasSpaces
  let name = serverName
    .replace(/[\s-]+/g, "-")                        // Normalize spaces/hyphens to single hyphen
    .replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())  // Convert -x to X (camelCase)
    .replace(/-([A-Z])/g, (_, letter) => letter)    // Remove hyphen before uppercase
    .replace(/-([0-9])/g, "$1")                     // Remove hyphen before numbers
    .replace(/-+/g, "")                             // Remove any remaining hyphens
    .replace(/[^a-zA-Z0-9_$]/g, "");                // Remove invalid characters

  // Ensure first letter is lowercase for camelCase
  if (name.length > 0 && /^[A-Z]/.test(name)) {
    name = name[0].toLowerCase() + name.slice(1);
  }

  // Handle names starting with digits or empty names
  if (!name || /^[0-9]/.test(name)) {
    name = "_" + (name || "mcp");
  }

  return name;
}

/**
 * Escape string for use in TypeScript string literal
 */
function escapeString(str) {
  if (!str) return "";
  return str
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");
}

/**
 * Indent multi-line code
 */
function indentCode(code, spaces) {
  const indent = " ".repeat(spaces);
  const lines = code.split("\n");
  return lines
    .map((line, i) => (i === 0 ? line : indent + line))
    .join("\n");
}

/**
 * Generate package.json for the extension
 * @param {object} options - Options
 * @param {string} options.name - Extension directory name
 * @param {string} options.packageName - Original MCP package name
 * @param {string} options.mcpCommand - Full MCP command
 * @param {string} [options.description] - Package description
 * @returns {string} - JSON string
 */
export function generateExtensionPackageJson(options) {
  const { name, packageName, mcpCommand, description } = options;

  const pkg = {
    name: `${name}-mcp-extension`,
    version: "1.0.0",
    type: "module",
    description: description || `Pi extension for ${name} MCP server`,
    mcp: {
      package: packageName,
      command: mcpCommand,
    },
    dependencies: {},
  };

  return JSON.stringify(pkg, null, 2);
}

/**
 * Generate README.md for the extension
 * @param {object} options - Options
 * @param {string} options.name - Extension directory name
 * @param {string} options.serverName - MCP server name
 * @param {string} options.packageName - Original MCP package name
 * @param {Array} options.groups - Tool groups
 * @param {Array} options.tools - Original MCP tools
 * @param {string} [options.description] - Package description
 * @returns {string} - Markdown content
 */
export function generateExtensionReadme(options) {
  const { name, serverName, packageName, groups, tools, description } = options;

  const desc = description || `Pi extension for ${serverName} MCP server`;

  const toolDocs = groups
    .map((group) => {
      const mcpToolsList = group.mcpTools.join(", ");
      const isMultiTool = group.mcpTools.length > 1;

      let section = `### ${group.label}\n\n`;
      section += `**Tool name:** \`${group.toolName}\`\n\n`;
      section += `${group.description}\n\n`;

      if (isMultiTool) {
        section += `**Actions:** ${group.mcpTools.map((t) => `\`${t}\``).join(", ")}\n\n`;
      }

      section += `*Wraps MCP tools:* ${mcpToolsList}\n`;

      return section;
    })
    .join("\n");

  return `# ${name}

${desc}

## Overview

This is a pi extension generated from the \`${packageName}\` MCP server.
It provides ${groups.length} grouped tool(s) wrapping ${tools.length} MCP tools.

## Installation

Extensions are auto-discovered by pi from \`~/.pi/agent/extensions/\`.

This extension was generated to:
\`\`\`
~/.pi/agent/extensions/${name}/
\`\`\`

## Tools

${toolDocs}

## Regeneration

To regenerate this extension from the latest MCP schema:

\`\`\`bash
mcp2ext refresh ${name}
\`\`\`

## Credits

This extension was generated by [mcp2ext](https://github.com/nicobailon/mcp-to-pi-tools).

MCP server: ${packageName}
`;
}

/**
 * Generate all extension files
 * @param {object} options - Generation options
 * @param {string} options.name - Extension directory name
 * @param {string} options.serverName - MCP server name
 * @param {string} options.mcpCommand - Full MCP command
 * @param {string} options.packageName - Original MCP package name
 * @param {Array} options.groups - Tool groups from AI grouping
 * @param {Array} options.tools - Original MCP tools with schemas
 * @param {string} [options.description] - Package description
 * @returns {object} - Map of filename to content
 */
export function generateExtensionFiles(options) {
  const files = {};

  // index.ts
  files["index.ts"] = generateExtension(options);

  // package.json
  files["package.json"] = generateExtensionPackageJson(options);

  // README.md
  files["README.md"] = generateExtensionReadme(options);

  return files;
}
